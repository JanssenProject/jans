#!/bin/bash
set -euo pipefail
# The below variable represents the top level directory of the repository
MAIN_DIRECTORY_LOCATION=$1
echo "Generate autogenerated documents"

# Compile jans-core to pick-up any changes in annotation processors
mvn -q -f "$MAIN_DIRECTORY_LOCATION"/jans-core/pom.xml -DskipTests clean compile install

# Compile modules where classes that use these annotations exist.
# This will generate markdown files under target/classes directory in respective module
# Compilation would also generate Swagger SPEC in any module which uses appropriate annotations and undergoes any change
mvn -q -f "$MAIN_DIRECTORY_LOCATION"/jans-auth-server/pom.xml clean compile
mvn -q -f "$MAIN_DIRECTORY_LOCATION"/jans-fido2/pom.xml clean compile
mvn -q -f "$MAIN_DIRECTORY_LOCATION"/jans-scim/pom.xml clean compile
mvn -q -f "$MAIN_DIRECTORY_LOCATION"/jans-config-api/pom.xml -DskipTests clean compile
mvn -q -f "$MAIN_DIRECTORY_LOCATION"/jans-lock/pom.xml -DskipTests clean compile

# Destination directories for the generated docs. Verify they exist first so a docs-tree
# rename (as happened when docs/admin became docs/janssen-server) fails loudly here
# instead of silently leaving the published docs stale.
PROPERTIES_DIR="$MAIN_DIRECTORY_LOCATION"/docs/janssen-server/reference/json/properties
FEATURE_FLAGS_DIR="$MAIN_DIRECTORY_LOCATION"/docs/janssen-server/reference/json/feature-flags
for d in "$PROPERTIES_DIR" "$FEATURE_FLAGS_DIR"; do
    if [ ! -d "$d" ]; then
        echo "ERROR: docs destination '$d' does not exist. Update this script to match the docs tree." >&2
        exit 1
    fi
done

# Move markdown files generated in respective modules by @DocFeatureFlag and @DocProperty annotations
mv -f "$MAIN_DIRECTORY_LOCATION"/jans-auth-server/model/target/classes/janssenauthserver-properties.md "$PROPERTIES_DIR"
mv -f "$MAIN_DIRECTORY_LOCATION"/jans-auth-server/model/target/classes/janssenauthserver-feature-flags.md "$FEATURE_FLAGS_DIR"
mv -f "$MAIN_DIRECTORY_LOCATION"/jans-fido2/model/target/classes/fido2-properties.md "$PROPERTIES_DIR"
mv -f "$MAIN_DIRECTORY_LOCATION"/jans-scim/model/target/classes/scim-properties.md "$PROPERTIES_DIR"
mv -f "$MAIN_DIRECTORY_LOCATION"/jans-config-api/common/target/classes/config-api-properties.md "$PROPERTIES_DIR"
mv -f "$MAIN_DIRECTORY_LOCATION"/jans-lock/lock-server/model/target/classes/lock-properties.md "$PROPERTIES_DIR"